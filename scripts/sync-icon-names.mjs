#!/usr/bin/env node
// Regenerate lib/iconNames.ts — the Material Symbols the site actually uses.
//
// Why: the full Material Symbols Rounded font is ~410 KB and loads on every
// page. Google Fonts can subset it (`&icon_names=a,b,c`) down to ~40 KB, but
// any icon left out of that list renders as its literal ligature text
// ("arrow_forward"). So the list has to be complete, and a hand-kept list
// would drift the first time someone adds an <Icon>.
//
// How: every quoted string literal and bare JSX text in the source is
// intersected with the set of real Material Symbols names
// (scripts/material-symbols-names.txt). That deliberately over-collects — a
// string "home" used for something else still adds the `home` glyph — but it
// also catches every dynamic case (`{item.icon}` fed from a config array,
// `cond ? "a" : "b"`) without having to understand the code. Each extra glyph
// costs ~100 bytes; a missing one is a visible bug.
//
// Admin-entered icons (block editor, NFC tiles, training categories, link
// blocks) are chosen from pickers that read ICON_NAMES, so they can't go
// outside the list either.
//
// Runs automatically before `dev` and `build` (see package.json), so the list
// can't go stale. Run by hand: npm run icons:sync
// Refresh the valid-name list from Google: npm run icons:sync -- --refresh
//
// It also self-hosts the subset font. Linking Google's stylesheet made every
// page wait on a render-blocking request to fonts.googleapis.com, then a second
// connection to fonts.gstatic.com for the font (served with only a 1-day
// cache) — PageSpeed's largest mobile FCP cost. So the same subset is
// downloaded once per icon list into public/fonts/ under a name keyed to the
// list (cached for a year, see next.config.ts), and lib/iconFont.ts points the
// inline @font-face in app/layout.tsx at it.

import { createHash } from "node:crypto";
import { readFile, readdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const NAMES_FILE = path.join(ROOT, "scripts/material-symbols-names.txt");
const OUT = path.join(ROOT, "lib/iconNames.ts");
const FONT_DIR = path.join(ROOT, "public/fonts");
const FONT_PREFIX = "material-symbols-rounded-";
const FONT_MODULE = path.join(ROOT, "lib/iconFont.ts");
// Google serves woff2 only to a browser it recognises.
const WOFF2_UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";
const SCAN_DIRS = ["app", "components", "lib", "contexts", "utils", "packages/shared/src"];
const CODEPOINTS_URL =
  "https://raw.githubusercontent.com/google/material-design-icons/master/variablefont/MaterialSymbolsRounded%5BFILL%2CGRAD%2Copsz%2Cwght%5D.codepoints";

async function loadValidNames() {
  if (process.argv.includes("--refresh")) {
    const res = await fetch(CODEPOINTS_URL);
    if (!res.ok) throw new Error(`codepoints fetch failed: ${res.status}`);
    const names = [...new Set((await res.text()).split("\n").map((l) => l.split(" ")[0]).filter(Boolean))].sort();
    await writeFile(NAMES_FILE, names.join("\n") + "\n");
    console.log(`🔄 Refreshed ${names.length} Material Symbols names`);
  }
  // \r?\n: a Windows checkout with core.autocrlf turns this file CRLF, and
  // "home\r" would match nothing, emptying the icon list.
  return new Set((await readFile(NAMES_FILE, "utf8")).split(/\r?\n/).filter(Boolean));
}

async function* walk(dir) {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (entry.name === "node_modules" || entry.name.startsWith(".")) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (/\.(tsx?|mjs|js)$/.test(entry.name)) yield full;
  }
}

const LITERAL = /["'`]([a-z][a-z0-9_]*)["'`]/g;
const JSX_TEXT = />\s*([a-z][a-z0-9_]*)\s*</g;

const valid = await loadValidNames();
const found = new Set();

for (const dir of SCAN_DIRS) {
  for await (const file of walk(path.join(ROOT, dir))) {
    // The generated list would otherwise keep every name alive forever.
    if (file === OUT) continue;
    const src = await readFile(file, "utf8");
    for (const re of [LITERAL, JSX_TEXT]) {
      for (const match of src.matchAll(re)) {
        if (valid.has(match[1])) found.add(match[1]);
      }
    }
  }
}

// Google requires icon_names in alphabetical order.
const names = [...found].sort();
const body = `// Generated by scripts/sync-icon-names.mjs — do not edit by hand.
// Runs before \`dev\` and \`build\`; see that script for how names are found.

/** Every Material Symbols name the site uses, sorted (Google requires it). */
export const ICON_NAMES = [
${names.map((n) => `  "${n}",`).join("\n")}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`;

let previous = "";
try {
  previous = await readFile(OUT, "utf8");
} catch {}

if (previous === body) {
  console.log(`✓ Icon list up to date (${names.length} icons)`);
} else {
  await writeFile(OUT, body);
  console.log(`📝 Wrote ${names.length} icons to lib/iconNames.ts`);
}

// ─── Self-hosted subset font ────────────────────────────────────────────────

async function downloadSubset(fontPath) {
  const cssUrl = `https://fonts.googleapis.com/css2?family=Material+Symbols+Rounded:opsz,wght,FILL,GRAD@24,500,0,0&icon_names=${names.join(",")}&display=block`;
  const cssRes = await fetch(cssUrl, { headers: { "User-Agent": WOFF2_UA } });
  if (!cssRes.ok) throw new Error(`stylesheet fetch failed: ${cssRes.status}`);
  const src = (await cssRes.text()).match(/src:\s*url\(([^)]+)\)\s*format\('woff2'\)/)?.[1];
  if (!src) throw new Error("no woff2 url in Google's stylesheet");
  const fontRes = await fetch(src);
  if (!fontRes.ok) throw new Error(`font fetch failed: ${fontRes.status}`);
  await writeFile(fontPath, Buffer.from(await fontRes.arrayBuffer()));
}

const hash = createHash("sha256").update(names.join(",")).digest("hex").slice(0, 12);
const fontFile = `${FONT_PREFIX}${hash}.woff2`;
const fontPath = path.join(FONT_DIR, fontFile);
const fontModule = `// Generated by scripts/sync-icon-names.mjs — do not edit by hand.

/** Self-hosted Material Symbols subset for the icons in lib/iconNames.ts. */
export const ICON_FONT_URL = "/fonts/${fontFile}";
`;

let haveFont = true;
try {
  await readFile(fontPath);
} catch {
  haveFont = false;
}

if (!haveFont) {
  try {
    await downloadSubset(fontPath);
    haveFont = true;
    console.log(`📝 Downloaded icon font subset to public/fonts/${fontFile}`);
  } catch (err) {
    // A deploy must never ship a font missing glyphs (they render as their
    // literal names), so CI fails. Offline local dev keeps the previous font:
    // only icons added since then show as text until the next online run.
    if (process.env.CI || process.env.VERCEL) {
      console.error(`❌ Could not download the icon font subset: ${err.message}`);
      process.exit(1);
    }
    console.warn(`⚠️  Icon font not updated (${err.message}); new icons will show as text until the next online run`);
  }
}

if (haveFont) {
  // Older subsets are dead weight in the deploy once the module moves on.
  for (const f of await readdir(FONT_DIR)) {
    if (f.startsWith(FONT_PREFIX) && f.endsWith(".woff2") && f !== fontFile) {
      await unlink(path.join(FONT_DIR, f));
    }
  }
  let previousModule = "";
  try {
    previousModule = await readFile(FONT_MODULE, "utf8");
  } catch {}
  if (previousModule !== fontModule) await writeFile(FONT_MODULE, fontModule);
}
